// Generate data/styles.js from data/styles.json so the dashboard works when opened via file://
import { readFileSync, writeFileSync } from "node:fs";
const json = JSON.parse(readFileSync(new URL("../data/styles.json", import.meta.url), "utf8"));
const out = "// AUTO-GENERATED by scripts/build-styles.mjs from data/styles.json. Do not edit by hand.\nwindow.STYLE_DATA = " + JSON.stringify(json, null, 2) + ";\n";
writeFileSync(new URL("../data/styles.js", import.meta.url), out);
console.log(`data/styles.js written (${json.styles.length} styles)`);
