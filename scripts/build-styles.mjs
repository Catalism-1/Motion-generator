// Generate data/*.js from data/*.json so the dashboard works when opened via file:// (no server needed).
import { readFileSync, writeFileSync } from "node:fs";
const build = (name, global) => {
  const json = JSON.parse(readFileSync(new URL(`../data/${name}.json`, import.meta.url), "utf8"));
  writeFileSync(new URL(`../data/${name}.js`, import.meta.url),
    `// AUTO-GENERATED by scripts/build-styles.mjs from data/${name}.json. Do not edit by hand.\nwindow.${global} = ${JSON.stringify(json, null, 2)};\n`);
  return json;
};
const s = build("styles", "STYLE_DATA"), e = build("elements", "ELEMENT_DATA");
console.log(`data/styles.js (${s.styles.length} styles), data/elements.js (${e.elements.length} elements) written`);
